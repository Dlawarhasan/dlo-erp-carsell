/** جیاکەرەوەکانی نێوان بەشەکانی دەقێکی پێکهاتوو — بۆ نمونە «هەولێر — گەڕەکی نوێ» */
const SEP = /(\s*(?:—|–|\||·|،|,|\/)\s*)/

/**
 * یەک نرخ وەردەگێڕێت بۆ عەرەبی.
 * دەقێکی پێکهاتوو بەش بە بەش تاقی دەکرێتەوە، و هەر بەشێک کە لە
 * فەرهەنگەکەدا نەبێت وەک خۆی دەمێنێتەوە (بۆ نمونە ناوی گەڕەک).
 */
export function toArabic(v?: string | number | null): string {
  if (v === null || v === undefined) return ''
  const s = String(v)
  if (!s.trim()) return s
  const direct = AR_VALUES[s.trim()]
  if (direct) return direct
  return s
    .split(SEP)
    .map((part, i) => (i % 2 === 1 ? part : AR_VALUES[part.trim()] || part))
    .join('')
}

/** ئەگەر زمانەکە عەرەبی بێت وەریدەگێڕێت، ئەگەرنا وەک خۆی دەیگەڕێنێتەوە */
export const langValue = (v: string | number | null | undefined, lang: 'ku' | 'ar') =>
  lang === 'ar' ? toArabic(v) : String(v ?? '')
